#!/usr/bin/env python3
"""Regenerate the files the theme layout derives from the directories.

Sources live in ``src/<theme>/`` and public headers in ``include/<theme>/``
(one level each; ``src/imp/`` and ``include/imp/`` are the connection layer
to IMP, ``include/internal/`` the private helpers). The directory a file sits
in *is* its theme, so nothing lists headers by hand. Two files follow from
the layout and are written here:

``src/ThemeSources.cpp``
    IMP's unity build (tools/build/setup_all.py) compiles ``src/*.cpp`` and
    ``src/internal/*.cpp`` and looks no deeper; this file ``#include``\\ s every
    themed source so the unity translation unit reaches them.

``include/<theme>.h``
    One umbrella header per theme, ``IMP/bff/<theme>.h``. IMP's all-header
    generator (tools/dev_tools/make_all_header.py) and its header linking
    (tools/build/setup.py) see only ``include/*.h``, so ``IMP/bff.h`` -- what
    the SWIG wrapper includes -- reaches the themed headers through these.

Run from the repository root after adding, moving or removing a source or a
public header; ``test/test_theme_headers.py`` fails until the output is current.
"""
import os
import re
import sys

LAYER = "imp"


def themes():
    text = open("src/Themes.cmake").read()
    m = re.search(r'set\(imp_bff_themes\s+"([^"]*)"\)', text)
    return [t for t in m.group(1).split(";") if t]


def theme_sources():
    """`ThemeSources.cpp`, by file name: the order the flat src/ directory had.

    The unity translation unit shares anonymous namespaces, so a different
    order can change which helper an unqualified name resolves to.
    """
    out = ["// IMP's unity build (tools/build/setup_all.py) compiles src/*.cpp and",
           "// src/internal/*.cpp into one translation unit and looks no deeper; the themed",
           "// sources are reached through this file, as the connection layer is through",
           "// ImpLayer.cpp. Per-cpp and standalone builds name the sources directly and",
           "// leave this file out. Generated by tools/dev/theme_layout.py;",
           "// test/test_theme_headers.py checks the list is complete.", ""]
    files = sorted((fn, theme) for theme in themes() for fn in os.listdir(f"src/{theme}")
                   if fn.endswith(".cpp"))
    out += [f'#include "{theme}/{fn}"' for fn, theme in files]
    return "\n".join(out) + "\n"


def umbrella(theme):
    """`include/<theme>.h`: every public header of one theme."""
    headers = sorted(fn for fn in os.listdir(f"include/{theme}") if fn.endswith(".h"))
    guard = f"IMPBFF_THEME_{theme.upper()}_H"
    what = ("the connection layer to IMP" if theme == LAYER else f"the `{theme}` theme")
    out = ["/**",
           f" * \\file IMP/bff/{theme}.h",
           f" * \\brief Every public header of {what}.",
           " *",
           " * Generated by tools/dev/theme_layout.py from include/%s/." % theme,
           " *",
           " * Copyright 2007-2026 IMP Inventors. All rights reserved.",
           " */",
           "",
           f"#ifndef {guard}",
           f"#define {guard}",
           ""]
    out += [f"#include <IMP/bff/{theme}/{h}>" for h in headers]
    out += ["", f"#endif /* {guard} */", ""]
    return "\n".join(out)


def outputs():
    """{path: content} of every generated file."""
    files = {"src/ThemeSources.cpp": theme_sources()}
    for theme in themes() + [LAYER]:
        files[f"include/{theme}.h"] = umbrella(theme)
    return files


def main():
    for path, content in outputs().items():
        old = open(path).read() if os.path.exists(path) else None
        if old != content:
            with open(path, "w") as fh:
                fh.write(content)
            print("wrote", path)


if __name__ == "__main__":
    sys.exit(main())
